"""Writes README.md from scripts/content.py.

    python scripts/readme.py

The live PR list between the OSS markers is kept as is; scripts/refresh.py owns it.
"""
from __future__ import annotations

import re
from pathlib import Path

from content import (ALSO, CALL_URL, FOOTER_LINKS, INTRO, LINKS, LLMSLIM, PROJECTS, RECOGNITION, LEAD, TOOLS,
                     WORK, EDUCATION)

ROOT = Path(__file__).resolve().parent.parent
GH = "https://github.com/Thanatos9404/"
SEP = " &nbsp;·&nbsp; "


def pic(name, alt, width=None, height=None):
    w = f' width="{width}"' if width else ""
    h = f' height="{height}"' if height else ""
    alt = alt.replace('"', "'")
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/{name}-dark.svg">'
            f'<img alt="{alt}" src="assets/{name}-light.svg"{w}{h}></picture>')


def a(href, inner):
    return f'<a href="{href}">{inner}</a>'


def section(out, name, alt):
    out += [pic(name, alt, "100%"), ""]


def build() -> str:
    o: list[str] = []
    o += ["<!-- Generated by scripts/readme.py from scripts/content.py. Visuals come from scripts/build.py; the open "
          "source wall, skyline and PR list are refreshed by scripts/refresh.py through GitHub Actions. -->", ""]
    o += [a("https://www.yashvardhan.tech", pic("hero", "Yashvardhan Thanvi. Founder of LLMSlim, AI engineer from "
                                                       "Jaipur, India. Available for freelance work.", "100%")), ""]
    o.append('<p align="center">')
    for href, name, label, _, _ in LINKS:
        o.append("  " + a(href, pic(name, label, height="44")))
    o += ["</p>", "", '<p align="center">', INTRO, "</p>", "", "<br>", ""]

    # 01
    section(o, "h-building", "01 Now building: Smaller context, better answers.")
    stats = ", ".join(f"{b} {l1} ({l2})" for b, l1, l2 in LLMSLIM["stats"])
    o += [a("https://www.llmslim.app", pic("llmslim", f"LLMSlim, the context layer for production AI agents. "
                                                     f"pip install llmslim. {stats}. Part of "
                                                     f"{len(LLMSLIM['programs'])} startup programs: "
                                                     f"{', '.join(LLMSLIM['programs'])}.", "100%")), ""]
    o += ['<p align="center">', "  " + SEP.join(a(h, t) for t, h in LLMSLIM["links"]), "</p>", "", "<br>", ""]

    # 02
    section(o, "h-work", "02 Selected work: Things I've built.")
    for i in range(0, len(PROJECTS), 2):
        pair = PROJECTS[i:i + 2]
        o.append('<p align="center">')
        for p in pair:
            o.append("  " + a(GH + p["repo"], pic(f"p-{p['key']}", f"{p['name']}: {p['desc']}", "49%")))
        notes = [p["name"] + " " + " and ".join(a(h, t) for t, h in p["links"]) for p in pair if p.get("links")]
        if notes:
            o.append(f"  <br><sub>{SEP.join(notes)}</sub>")
        o += ["</p>", ""]
    if ALSO:
        o += ['<p align="center"><sub>', "Also " + SEP.join(f"{a(h, n)}, {d}" for n, h, d in ALSO), "</sub></p>", ""]
    o += ["<br>", ""]

    # 03
    section(o, "h-oss", "03 Open source: Pull requests to the tools I use.")
    o += [pic("oss", "Open source pull requests grouped by organisation, with merged and in-review counts.", "100%"),
          "", "<!-- OSS:START -->", "<!-- OSS:END -->", "", "<br>", ""]

    # 04
    section(o, "h-proud", "04 Recognition: A few proud moments.")
    feat, side = RECOGNITION["feature"], RECOGNITION["side"]
    rec = ["".join(x[0] for x in feat["title"]) + ", " + feat["eyebrow"].split("  ")[0] + ".", feat["body"],
           f"{side['eyebrow'].title()}: {side['title']} {side['body']}."]
    rec += [f"{t}: {b}, {d}." for b, t, d in RECOGNITION["tiles"]]
    section(o, "recognition", " ".join(rec))
    o += ["<br>", ""]

    # 05
    section(o, "h-path", "05 Experience: Where I've worked and led.")
    exp = [f"{org}, {role}, {when.lower()}." for org, role, when, _ in WORK]
    exp += [f"{org}, {role}." for org, role, _ in LEAD]
    exp.append(f"{EDUCATION['school']}, {EDUCATION['degree']}, {EDUCATION['score_label']} {EDUCATION['score']}.")
    section(o, "experience", " ".join(exp))
    o += ["<br>", ""]

    # 06
    section(o, "h-activity", "06 Activity: Shipping, most days.")
    section(o, "skyline", "A 3D skyline of GitHub contributions over the last twelve months.")
    o += ["<br>", ""]

    # 07
    section(o, "h-tools", "07 Toolbox: On my workbench.")
    section(o, "toolbox", ", ".join(sum(TOOLS, [])) + ".")
    o += ["<br>", ""]

    # contact
    o += [a(CALL_URL, pic("contact", "Available for freelance. Have something in mind? Let's build it. Book a 30 "
                                     "minute call.", "100%")), ""]
    o += ['<p align="center">', "  " + SEP.join(a(h, t) for t, h in FOOTER_LINKS), "  <br><br>",
          "  <sub>Every visual here is a hand-built, animated SVG. The open source wall, skyline and PR list "
          "refresh themselves through the day.</sub>", "</p>"]
    return "\n".join(o) + "\n"


def main():
    path = ROOT / "README.md"
    new = build()
    if path.exists():
        old = path.read_text(encoding="utf-8")
        m = re.search(r"<!-- OSS:START -->.*?<!-- OSS:END -->", old, flags=re.S)
        if m:
            new = new.replace("<!-- OSS:START -->\n<!-- OSS:END -->", m.group(0))
    path.write_text(new, encoding="utf-8", newline="\n")
    print("README.md written")


if __name__ == "__main__":
    main()
