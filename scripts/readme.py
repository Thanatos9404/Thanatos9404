"""Writes README.md from scripts/content.py and assets/live.json.

    python scripts/readme.py

The live PR list between the OSS markers is kept as is; scripts/refresh.py owns it.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from content import FOOTER_LINKS, FRESH_MAX, LINKS, LLMSLIM, MORE, NAV, PROJECTS, STACK, STACK_ALSO, CALL_URL

ROOT = Path(__file__).resolve().parent.parent
GH = "https://github.com/Thanatos9404/"
SEP = " &nbsp;·&nbsp; "


def load_live() -> dict:
    try:
        return json.loads((ROOT / "assets" / "live.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def pic(name, alt, width=None, height=None, folder="assets"):
    w = f' width="{width}"' if width else ""
    h = f' height="{height}"' if height else ""
    alt = alt.replace('"', "'")
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{folder}/{name}-dark.svg">'
            f'<img alt="{alt}" src="{folder}/{name}-light.svg"{w}{h}></picture>')


def a(href, inner):
    return f'<a href="{href}">{inner}</a>'


def build() -> str:
    live = load_live()
    ll = live.get("llmslim", {})
    o: list[str] = []
    o += ["<!-- Generated by scripts/readme.py from scripts/content.py and assets/live.json. Visuals: scripts/build.py. "
          "Live data: scripts/refresh.py, run by .github/workflows/refresh.yml. -->", ""]

    # Hero, navigation, buttons
    o += [a("https://www.yashvardhan.tech", pic(
        "hero", "Yashvardhan Thanvi. Founder of LLMSlim, the open-source context layer for production AI agents, "
                "backed by 15 startup programs. Runs AMEYOR, an AI and software studio. Previously AI/ML research at "
                "DRDO. Available for freelance work.", "100%")), ""]
    o += ['<p align="center">', "  " + SEP.join(a(f"#{anchor}", text) for text, anchor in NAV), "</p>", ""]
    o.append('<p align="center">')
    for href, name, text, _, _ in LINKS:
        o.append("  " + a(href, pic(name, text, height="40")))
    o += ["</p>", ""]
    merged_orgs = [x["name"] for x in live.get("org_list", []) if x.get("merged")]
    if merged_orgs:
        o += [pic("merged", f"Pull requests merged at {', '.join(merged_orgs[:10])} and more.", "100%"), ""]

    # LLMSlim
    o += ["## LLMSlim", ""]
    stats = "; ".join(f"{b} {l} ({src})" for b, l, src in LLMSLIM["stats"])
    o += [a("https://www.llmslim.app", pic(
        "llmslim", f"LLMSlim {('v' + ll['version']) if ll.get('version') else ''}: {LLMSLIM['tagline']} {stats}. "
                   f"Backed by {', '.join(LLMSLIM['program_names'])}.", "100%")), ""]
    o += ['<p align="center">', "  " + SEP.join(a(h, t) for t, h in LLMSLIM["links"]), "</p>", ""]

    # Work
    o += ["## Selected work", ""]
    for i in range(0, len(PROJECTS), 2):
        pair = PROJECTS[i:i + 2]
        o.append('<p align="center">')
        for p in pair:
            o.append("  " + a(GH + p["repo"], pic(f"p-{p['shot']}", f"{p['name']}: {p['line']}. {p['tag'].title()}.",
                                                  "49%")))
        notes = [f"{p['name']}: " + " · ".join(a(h, t) for t, h in p["links"]) for p in pair if p.get("links")]
        if notes:
            o.append(f"  <br><sub>{SEP.join(notes)}</sub>")
        o += ["</p>", ""]
    fresh = live.get("fresh", [])[:FRESH_MAX]
    featured = {p["repo"].lower() for p in PROJECTS}
    rows, seen = [], set()
    for item in fresh:
        if item["repo"].lower() in featured:
            continue
        seen.add(item["repo"].lower())
        seen.add(item["name"].lower())
        rows.append(f"- **[{item['name']}]({item['url']})** <sub>new</sub> {item['desc'].rstrip('.')}."
                    + (f" [Live]({item['homepage']})" if item.get("homepage") else ""))
    for name, href, desc in MORE:
        if name.lower() in seen or href.rstrip("/").rsplit("/", 1)[-1].lower() in seen:
            continue
        rows.append(f"- **[{name}]({href})** {desc[0].upper() + desc[1:]}.")
    if rows:
        o += ["<details>", f"<summary><b>More projects</b> ({len(rows)})</summary>", "", *rows, "", "</details>", ""]

    # Open source
    o += ["## Open source", ""]
    if live.get("org_list"):
        o += [pic("oss", f"{live['prs']} pull requests to {live['orgs']} organisations, {live['merged']} merged. "
                         f"Merged at {', '.join(merged_orgs[:12])}.", "100%"), ""]
    listed = live.get("listed_in", [])
    integ = [x for x in listed if x.get("kind") == "integration"]
    lists = [x for x in listed if x.get("kind", "list") == "list"]
    bits = []
    if integ:
        bits.append("ships in " + " and ".join("the " + a(x["url"], x["name"]) for x in integ[:3]))
    if lists:
        top = [a(x["url"], x["name"]) for x in lists[:3]]
        bits.append(f"is listed in {len(lists)} curated lists, including {', '.join(top[:-1])} and {top[-1]}"
                    if len(top) > 1 else f"is listed in {top[0]}")
    if bits:
        o += [f'<p align="center"><sub>LLMSlim {", and ".join(bits)}.</sub></p>', ""]
    o += ["<!-- OSS:START -->", "<!-- OSS:END -->", ""]

    # Recognition, experience, stack, activity
    o += ["## Recognition", "", pic("recognition", "Recognition: VBYLD 2026 Rajasthan Rank 1, NASA Space Apps Global "
                                                   "Finalist Nominee, IETE first places, Product Hunt #11, Polaris "
                                                   "Fellowship final round, SIH 2026, HackLoop top 10.", "100%"), ""]
    o += ["## Experience", "", pic("experience", "Experience: DRDO Scientific Analysis Group research intern, founder "
                                                 "of AMEYOR, Olinp Technologies AI/ML intern; AWS Student Builder Group "
                                                 "Leader, GeeksforGeeks Campus Mantri, IIC Head, GDG on Campus, Google "
                                                 "Gemini Student Ambassador, OnePlus, GSSoC. BCA at BIT Mesra, CGPA "
                                                 "9.35.", "100%"), ""]
    o += ["## Stack", "", pic("stack", ", ".join(sum(STACK, [])), "100%"), "",
          f'<p align="center"><sub>Also {STACK_ALSO}.</sub></p>', ""]
    if (ROOT / "profile-3d-contrib" / "profile-dark.svg").exists():
        o += ["## Activity", "", '<picture><source media="(prefers-color-scheme: dark)" '
                                 'srcset="profile-3d-contrib/profile-dark.svg"><img alt="3D contribution calendar for '
                                 'the last year, with contribution types and top languages" '
                                 'src="profile-3d-contrib/profile-light.svg" width="100%"></picture>', ""]

    # Contact
    o += ["## Contact", "", a(CALL_URL, pic("contact", "Have something in mind? Let's build it. Book a 30-min call.",
                                            "100%")), ""]
    o += ['<p align="center">', "  " + SEP.join(a(h, t) for t, h in FOOTER_LINKS), "</p>"]
    return "\n".join(o) + "\n"


def main():
    path = ROOT / "README.md"
    new = build()
    if path.exists():
        m = re.search(r"<!-- OSS:START -->.*?<!-- OSS:END -->", path.read_text(encoding="utf-8"), flags=re.S)
        if m:
            new = new.replace("<!-- OSS:START -->\n<!-- OSS:END -->", m.group(0))
    path.write_text(new, encoding="utf-8", newline="\n")
    print("README.md written")


if __name__ == "__main__":
    main()
